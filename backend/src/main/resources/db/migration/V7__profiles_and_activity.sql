CREATE TABLE account_profiles (
 user_id UUID PRIMARY KEY REFERENCES app_users(id),
 phone VARCHAR(30) NOT NULL DEFAULT '',
 bio VARCHAR(2000) NOT NULL DEFAULT '',
 specialisation VARCHAR(150) NOT NULL DEFAULT ''
);
CREATE TABLE activity_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id UUID NOT NULL REFERENCES app_users(id), actor_name VARCHAR(100) NOT NULL,
 request_method VARCHAR(10) NOT NULL, route VARCHAR(300) NOT NULL,
 response_status INTEGER NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX activity_events_created_idx ON activity_events(created_at);
