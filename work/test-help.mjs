import assert from 'node:assert/strict'
import { answerQuestion,helpContext,whatsappUrl } from '../src/helpKnowledge.js'
const context=helpContext()
assert.match(answerQuestion('What are the course fees?',context).text,/40,000/)
assert.match(answerQuestion('How much is GenAI?',context).text,/40,000/)
assert.equal(answerQuestion('Software testing syllabus',context).links.length,2)
assert.equal(answerQuestion('Selenium brochure',context).links.length,2)
assert.match(answerQuestion('What is the refund policy?',context).text,/proposed draft/)
assert.match(answerQuestion('I forgot my password',context).text,/not configured/)
assert.match(answerQuestion('How do I upload an assignment?',context).text,/Submit \/ replace file/)
assert.match(answerQuestion('Can I pay by UPI?',context).text,/not connected/)
assert.match(answerQuestion('Is placement guaranteed?',context).text,/does not guarantee/)
assert.match(answerQuestion('How do I join a live class?',context).text,/Asia\/Kolkata/)
assert.match(answerQuestion('Can I get a certificate?',context).text,/administrator reviews eligibility/)
assert.equal(answerQuestion('Who won the cricket match?',context).unanswered,true)
assert.match(answerQuestion('What is its fee?',context,['Tell me about GenAI']).text,/GenAI/)
assert.doesNotMatch(answerQuestion('What is its fee?',context,['Tell me about GenAI']).text,/Software Testing/)
const custom=helpContext({settings:{email:'support@example.com',phone:'+91 99999 99999'},courses:[{id:'ai',name:'GenAI',published:true,price:12345,description:'Custom',duration:'8 weeks'}]})
assert.match(answerQuestion('GenAI fees',custom).text,/12,345/)
assert.match(answerQuestion('contact support',custom).text,/support@example.com/)
const url=new URL(whatsappUrl('+91 88707 83300','Hello & help? #course'))
assert.equal(url.hostname,'wa.me');assert.equal(url.pathname,'/918870783300');assert.equal(url.searchParams.get('text'),'Hello & help? #course')
assert.equal(whatsappUrl('8870783300',''), 'https://wa.me/918870783300')
assert.equal(whatsappUrl('not configured','test'),null)
console.log('English help intent routing, live catalogue fees, follow-up context, honest fallback and WhatsApp message encoding checks passed.')
